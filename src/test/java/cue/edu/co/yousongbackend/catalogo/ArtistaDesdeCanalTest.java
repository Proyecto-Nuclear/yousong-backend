package cue.edu.co.yousongbackend.catalogo;

import static org.assertj.core.api.Assertions.assertThat;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.junit.jupiter.params.provider.NullAndEmptySource;
import org.junit.jupiter.params.provider.ValueSource;

class ArtistaDesdeCanalTest {

    @ParameterizedTest
    @CsvSource(delimiter = '|', value = {
            "Juanes - Topic|Juanes",
            "Juanes - topic|Juanes",
            "Juanes - TOPIC|Juanes",
            "  Juanes   -   Topic  |Juanes",
            "Juanes-Topic|Juanes",
            "ShakiraVEVO|Shakira",
            "ShakiraVevo|Shakira",
            "shakiravevo|shakira",
            "Shakira VEVO|Shakira",
            "Carlos Vives|Carlos Vives",
            "Topic Records|Topic Records",
            "Vevo Fans Club|Vevo Fans Club",
            "Los Ángeles Azules - Topic|Los Ángeles Azules",
            "AC/DC - Topic|AC/DC",
            "Rock - Topic - Topic|Rock - Topic"
    })
    void stripsAutoGeneratedSuffixes(String canal, String artista) {
        assertThat(ArtistaDesdeCanal.de(canal)).isEqualTo(artista);
    }

    @ParameterizedTest
    @NullAndEmptySource
    @ValueSource(strings = {"   ", " - Topic", "VEVO", "vevo "})
    void answersNullWhenNothingUsefulIsLeft(String canal) {
        assertThat(ArtistaDesdeCanal.de(canal)).isNull();
    }

    @Test
    void theVerifiedArtistWinsOverTheChannelLabel() {
        assertThat(ArtistaDesdeCanal.etiqueta("Juanes", "Otro canal - Topic")).isEqualTo("Juanes");
        assertThat(ArtistaDesdeCanal.etiqueta(null, "Otro canal - Topic")).isEqualTo("Otro canal");
        assertThat(ArtistaDesdeCanal.etiqueta("  ", "Otro canal")).isEqualTo("Otro canal");
        assertThat(ArtistaDesdeCanal.etiqueta(null, null)).isNull();
    }

    @Test
    void aChannelLabelIsNeverVerified() {
        assertThat(ArtistaDesdeCanal.verificado("Juanes")).isTrue();
        assertThat(ArtistaDesdeCanal.verificado(null)).isFalse();
        assertThat(ArtistaDesdeCanal.verificado(" ")).isFalse();
    }
}
